-- ---------- 1. 数据表 ----------
create table if not exists public.name_history (
  id               bigint generated by default as identity primary key,
  user_requirement text        not null,
  name_result      text        not null,
  model_name       text        not null,
  created_at       timestamptz not null default now()
);

comment on table  public.name_history is 'AI 起名历史记录';
comment on column public.name_history.user_requirement is '用户填写的起名需求';
comment on column public.name_history.name_result      is 'AI 生成的名字方案（完整文本）';
comment on column public.name_history.model_name       is '生成时使用的模型';

-- ---------- 2. 索引：按时间倒序取最近记录 ----------
create index if not exists idx_name_history_created_at
  on public.name_history (created_at desc);

-- ---------- 3. 权限（RLS） ----------
alter table public.name_history enable row level security;

-- 【方案 A：课堂调试用】允许 anon key 读写，跑通功能最快
-- 风险：匿名密钥一旦泄露，任何人都能往表里写数据、读全部记录
drop policy if exists debug_anon_all on public.name_history;
create policy debug_anon_all on public.name_history
  for all to anon
  using (true) with check (true);

